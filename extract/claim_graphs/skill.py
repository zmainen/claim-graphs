TOKEN_RE = re.compile(r"\{\{([a-z0-9-]+)\}\}")


# ── render, write and check ──────────────────────────────────────────────


def render(name: str, root: Path | None = None) -> str:
    root = root or _repo_root()
    src = root / SOURCE_DIR / name
    if not src.is_file():
        raise FileNotFoundError(f"skill source missing: {src}")
    text = src.read_text(encoding="utf-8")
    if "{{generated-note}}" not in text:
        raise ValueError(f"{SOURCE_DIR}/{name} has no {{{{generated-note}}}} — a rendered file "
                         f"that does not say it is rendered will be edited in place")

    def sub(m: re.Match) -> str:
        tok = m.group(1)
        if tok not in TOKENS:
            raise ValueError(f"{SOURCE_DIR}/{name}: unknown token {{{{{tok}}}}}; "
                             f"known: {', '.join(sorted(TOKENS))}")
        return TOKENS[tok](root, name)

    out = TOKEN_RE.sub(sub, text)
    return out if out.endswith("\n") else out + "\n"


def generated(root: Path | None = None) -> dict[str, str]:
    root = root or _repo_root()
    return {name: render(name, root) for name in FILES}


def write(root: Path | None = None) -> list[Path]:
    root = root or _repo_root()
    out = []
    for name, text in generated(root).items():
        p = root / SKILL_DIR / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        out.append(p)
    return out


def check(root: Path | None = None) -> list[str]:
    """Names of committed skill files that differ from what the sources generate."""
    root = root or _repo_root()
    stale = []
    for name, text in generated(root).items():
        p = root / SKILL_DIR / name
        if not p.is_file() or p.read_text(encoding="utf-8") != text:
            stale.append(name)
    return stale
