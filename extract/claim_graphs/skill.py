"""The skill: what an agent is told, rendered from what the machinery declares.

An agent that loads the skill and an agent that runs the CLI must be doing the same thing.
They were not. The skill was written by hand from memory of this repository and then drifted
from it: it omitted `in-tension-with` entirely, still called `dissociates-with` an opposition
after the #125 ruling moved it out, and offered an `epistemic` value (`contested`) that no
claim file uses. A tree built by following it would have used the retired relation for the
case the ruling split off.

That is the same failure `contract.py` exists to prevent one level down, so this is the same
answer: the skill is *rendered*. Prose that carries judgment — what to look for in a paper,
which pairs of relations people confuse, what to report when handing a structure over — is
written by hand in `docs/skill/`. Everything that is declared somewhere is substituted into it
at build time from the declaration:

    scripts/relations.py           relations, direction, corpus examples, confusable pairs
    scripts/check_relations.py     the rules the gate enforces, so advice and gate agree
    claim_graphs/vocabulary.py     roles, claim types, confidence
    schema/to_claim_set.py         the closed value sets the interchange form accepts
    pipeline/layers.yaml           the sequence, so a runbook cannot list a layer that moved
    contract.py                    the vocabulary the model is actually sent, verbatim

`skill --check` fails when the committed skill is not what those sources generate, and
`make check` runs it. An unknown `{{token}}` fails generation rather than being rendered as a
word, the convention the site build already uses.

Like the contract, some tokens quote real claims, so a corpus checkout is needed to regenerate
or verify. The rendered skill is committed and ships without one.
"""

